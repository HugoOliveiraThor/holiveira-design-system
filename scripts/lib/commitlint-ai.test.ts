import { spawnSync } from 'node:child_process';
import { mkdtempSync, rmSync, writeFileSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { afterAll, beforeAll, describe, expect, it } from 'vitest';

import noAiMentionsPlugin, {
  FAILURE_MESSAGE,
  noAiMentions,
} from '../../commitlint/no-ai-mentions.mjs';

const ROOT = process.cwd();
const COMMITLINT = join(ROOT, 'node_modules', '.bin', 'commitlint');

type RuleResult = [boolean, string];

function rule(header: string, body = '', footer = ''): RuleResult {
  return noAiMentions({ header, body, footer }, 'always', true) as RuleResult;
}

function passes(header: string, body = '', footer = ''): boolean {
  return rule(header, body, footer)[0];
}

describe('commitlint ai rule', () => {
  it('rejects a commit that mentions an ai vendor', () => {
    const [valid, message] = rule('feat: add button', 'Generated with Claude');
    expect(valid).toBe(false);
    expect(message).toContain(FAILURE_MESSAGE);
    expect(message).toContain('Claude');

    for (const vendor of ['DeepSeek', 'ChatGPT', 'Copilot', 'Anthropic', 'OpenAI']) {
      expect(passes(`feat: ${vendor} wrote this`), vendor).toBe(false);
    }
    expect(
      passes('chore: tidy', '', 'Co-authored-by: Claude <noreply@anthropic.com>'),
      'vendor trailer',
    ).toBe(false);
  });

  it('allows a dependabot co-author and never matches a bare ai', () => {
    expect(
      passes(
        'chore(deps): bump vite',
        '',
        'Co-authored-by: dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>',
      ),
    ).toBe(true);
    for (const header of [
      'feat: add ai helper',
      'feat(ai): add prompt buffer',
      'docs: explain the ai config',
      'fix: corrige aí o layout',
    ]) {
      expect(passes(header), header).toBe(true);
    }
  });

  it('checks the header, the body and the footer', () => {
    expect(passes('feat: ship Claude support')).toBe(false);
    expect(passes('feat: ship', 'Co-written by DeepSeek')).toBe(false);
    expect(passes('feat: ship', '', 'Co-authored-by: OpenAI <dev@openai.com>')).toBe(false);
  });

  it('rejects a stated ai generation', () => {
    for (const statement of [
      'generated with ai',
      'AI-assisted refactor',
      'generated by an AI',
      'written by AI',
    ]) {
      expect(passes('feat: x', statement), statement).toBe(false);
    }
  });

  it('rejects a robot emoji', () => {
    expect(passes('feat: ship the docs 🤖')).toBe(false);
  });

  it('registers the rule in the plugin', () => {
    expect(noAiMentionsPlugin.rules['no-ai-mentions']).toBe(noAiMentions);
  });

  describe('commitlint CLI', () => {
    let dir: string;

    beforeAll(() => {
      dir = mkdtempSync(join(tmpdir(), 'commitlint-ai-'));
    });

    afterAll(() => {
      rmSync(dir, { recursive: true, force: true });
    });

    function lint(message: string): { code: number | null; output: string } {
      const file = join(dir, `message-${Math.random().toString(36).slice(2)}.txt`);
      writeFileSync(file, message);
      const result = spawnSync(COMMITLINT, ['--edit', file], { cwd: ROOT, encoding: 'utf8' });
      return { code: result.status, output: `${result.stdout ?? ''}${result.stderr ?? ''}` };
    }

    it('applies the rule through commitlint.config.mjs', () => {
      const rejected = lint('feat: x\n\nGenerated with Claude\n');
      expect(rejected.code).not.toBe(0);
      expect(rejected.output).toContain('no-ai-mentions');

      const dependabot = lint(
        'chore(deps): bump vite\n\nCo-authored-by: dependabot[bot] <49699333+dependabot[bot]@users.noreply.github.com>\n',
      );
      expect(dependabot.code).toBe(0);

      expect(lint('feat: add ai helper\n').code).toBe(0);
    });
  });
});
